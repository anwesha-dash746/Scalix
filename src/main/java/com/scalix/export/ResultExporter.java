package com.scalix.export;

import com.scalix.config.SimulationConfig;
import com.scalix.metrics.CostModel;
import com.scalix.metrics.DecisionRecord;
import com.scalix.metrics.RequestRecord;
import com.scalix.metrics.RunResult;
import com.scalix.metrics.RunSummary;
import com.scalix.metrics.TimeSeriesPoint;
import com.scalix.metrics.VmRecord;
import com.scalix.workload.WorkloadSpec;

import java.io.IOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Writes an experiment's results as CSV files into one directory:
 * <ul>
 *   <li>{@code summary.csv} — one row per run: ids, configuration, aggregated metrics</li>
 *   <li>{@code timeseries.csv} — one row per run per tick (VM counts, utilization, arrivals)</li>
 *   <li>{@code scaling_events.csv} — one row per policy evaluation, with reason and resulting VM count</li>
 *   <li>{@code workloads.csv} — parameters of every workload used</li>
 *   <li>{@code vms.csv} — lifetime and calculated cost of every VM</li>
 *   <li>{@code metric_definitions.csv} — which columns are MEASURED, CALCULATED or CONFIG</li>
 *   <li>{@code config_used.properties} — the full effective configuration</li>
 *   <li>{@code requests.csv} — optional, one row per request ({@code export.requests=true})</li>
 * </ul>
 */
public final class ResultExporter {

    /** Column → [kind, definition]. Kept next to the writer so the two cannot drift apart. */
    static final Map<String, String[]> SUMMARY_COLUMNS = new LinkedHashMap<>();

    static {
        col("run_id", "ID", "Unique run identifier: <experiment>-<workload>-<policy>");
        col("experiment_id", "ID", "Experiment (batch) identifier");
        col("workload_type", "CONFIG", "Workload pattern");
        col("policy", "CONFIG", "Scaling policy");
        col("master_seed", "CONFIG", "simulation.seed");
        col("workload_seed", "CONFIG", "Seed derived from master seed and workload type");
        col("workload_duration_s", "CONFIG", "Arrival phase length (simulated seconds)");
        col("workload_params", "CONFIG", "Rate parameters of the workload (requests/s, seconds)");
        col("decision_interval_s", "CONFIG", "Policy evaluation interval");
        col("tick_s", "CONFIG", "Controller tick (dispatch and sampling period)");
        col("vm_pes", "CONFIG", "PEs per VM");
        col("vm_mips_per_pe", "CONFIG", "MIPS per VM PE");
        col("vm_boot_s", "CONFIG", "Delay before a scaled-up VM accepts traffic");
        col("request_mean_length_mi", "CONFIG", "Mean request length (million instructions)");
        col("pricing_model", "CONFIG", "Assumed pricing model parameters");
        col("policy_params", "CONFIG", "Policy parameters (k=v;k=v)");
        col("requests_total", "MEASURED", "Requests generated by the workload");
        col("requests_completed", "MEASURED", "Requests whose Cloudlet finished in CloudSim Plus");
        col("requests_unfinished", "MEASURED", "Requests not finished when the run stopped");
        col("avg_response_time_s", "MEASURED", "Mean (finish - arrival) over completed requests");
        col("p50_response_time_s", "MEASURED", "Median response time (linear interpolation)");
        col("p95_response_time_s", "MEASURED", "95th-percentile response time (linear interpolation)");
        col("p99_response_time_s", "MEASURED", "99th-percentile response time (linear interpolation)");
        col("max_response_time_s", "MEASURED", "Maximum response time");
        col("avg_wait_time_s", "MEASURED", "Mean (execution start - arrival): balancer + VM queueing");
        col("avg_service_time_s", "MEASURED", "Mean (finish - execution start)");
        col("cpu_utilization", "MEASURED", "Busy PE-seconds of completed requests / provisioned PE-seconds of all VMs (incl. boot and drain)");
        col("mean_active_vm_utilization", "MEASURED", "Mean over ticks of the average Vm.getCpuPercentUtilization() across ACTIVE VMs");
        col("avg_billable_vms", "MEASURED", "Mean over ticks of ACTIVE+BOOTING+DRAINING VMs");
        col("peak_billable_vms", "MEASURED", "Maximum ACTIVE+BOOTING+DRAINING VMs at any tick");
        col("min_provisioned_vms", "MEASURED", "Minimum ACTIVE+BOOTING VMs at any tick");
        col("vm_seconds", "MEASURED", "Sum of VM lifetimes (request to destruction/run end)");
        col("billed_vm_seconds", "CALCULATED", "VM-seconds after applying billing granularity and minimum");
        col("total_cost_usd", "CALCULATED", "billed_vm_seconds / 3600 * price per VM-hour (assumed pricing model)");
        col("scale_up_actions", "MEASURED", "Decisions that added at least one VM");
        col("scale_down_actions", "MEASURED", "Decisions that removed at least one VM");
        col("total_scaling_actions", "MEASURED", "scale_up_actions + scale_down_actions");
        col("vms_added", "MEASURED", "Total VMs added by scale-ups");
        col("vms_removed", "MEASURED", "Total VMs removed by scale-downs");
        col("cooldown_suppressions", "MEASURED", "Decisions where a cooldown blocked an action");
        col("sim_end_time_s", "MEASURED", "Simulated time when the run stopped");
        col("drain_timed_out", "MEASURED", "true if the run hit simulation.maxDrainSeconds with work left");
        col("wall_clock_ms", "MEASURED", "Real time taken by the run (host-machine dependent)");
    }

    private static void col(String name, String kind, String def) {
        SUMMARY_COLUMNS.put(name, new String[] {kind, def});
    }

    private ResultExporter() { }

    public static void export(Path dir, String experimentId, SimulationConfig cfg, List<RunResult> runs) throws IOException {
        Files.createDirectories(dir);
        final CostModel cost = CostModel.fromConfig(cfg);
        writeSummary(dir.resolve("summary.csv"), experimentId, cfg, cost, runs);
        writeTimeSeries(dir.resolve("timeseries.csv"), runs);
        writeDecisions(dir.resolve("scaling_events.csv"), runs);
        writeWorkloads(dir.resolve("workloads.csv"), experimentId, runs);
        writeVms(dir.resolve("vms.csv"), cost, runs);
        writeDefinitions(dir.resolve("metric_definitions.csv"));
        writeConfig(dir.resolve("config_used.properties"), experimentId, cfg);
        if (cfg.exportRequests()) {
            writeRequests(dir.resolve("requests.csv"), runs);
        }
    }

    private static void writeSummary(Path file, String experimentId, SimulationConfig cfg, CostModel cost,
                                     List<RunResult> runs) throws IOException {
        try (CsvWriter w = new CsvWriter(file, new ArrayList<>(SUMMARY_COLUMNS.keySet()))) {
            for (RunResult r : runs) {
                final RunSummary s = RunSummary.of(r, cost);
                final WorkloadSpec ws = r.workload();
                w.writeRow(r.runId(), experimentId, ws.type(), r.policyName(), cfg.seed(), ws.seed(),
                    ws.durationSeconds(), ws.paramsString(), cfg.decisionIntervalSeconds(), cfg.tickSeconds(),
                    cfg.vmPes(), cfg.vmMipsPerPe(), cfg.vmBootSeconds(), cfg.requestMeanLengthMi(), cost.describe(),
                    kv(r.policyParameters()),
                    s.requestsTotal(), s.requestsCompleted(), s.requestsUnfinished(),
                    s.avgResponseTime(), s.p50ResponseTime(), s.p95ResponseTime(), s.p99ResponseTime(),
                    s.maxResponseTime(), s.avgWaitTime(), s.avgServiceTime(),
                    s.cpuUtilization(), s.meanActiveVmUtilization(), s.avgBillableVms(), s.peakBillableVms(),
                    s.minProvisionedVms(), s.vmSeconds(), s.billedVmSeconds(), s.totalCost(),
                    s.scaleUpActions(), s.scaleDownActions(), s.totalScalingActions(), s.vmsAdded(), s.vmsRemoved(),
                    s.cooldownSuppressions(), s.simEndTime(), s.drainTimedOut(), r.wallClockMillis());
            }
        }
    }

    private static void writeTimeSeries(Path file, List<RunResult> runs) throws IOException {
        try (CsvWriter w = new CsvWriter(file, List.of("run_id", "workload_type", "policy", "time_s",
            "provisioned_vms", "active_vms", "booting_vms", "draining_vms", "billable_vms",
            "active_vm_utilization", "arrivals_in_tick", "requests_in_system"))) {
            for (RunResult r : runs) {
                for (TimeSeriesPoint p : r.timeSeries()) {
                    w.writeRow(r.runId(), r.workload().type(), r.policyName(), p.time(), p.provisionedVms(),
                        p.activeVms(), p.bootingVms(), p.drainingVms(), p.billableVms(), p.utilization(),
                        p.arrivals(), p.inSystem());
                }
            }
        }
    }

    private static void writeDecisions(Path file, List<RunResult> runs) throws IOException {
        try (CsvWriter w = new CsvWriter(file, List.of("run_id", "workload_type", "policy", "time_s", "action",
            "requested_delta", "applied_delta", "fleet_changed", "vms_before", "vms_after", "interval_utilization",
            "interval_arrival_rate", "trend", "relative_slope", "cooldown_blocked", "reason"))) {
            for (RunResult r : runs) {
                for (DecisionRecord d : r.decisions()) {
                    w.writeRow(r.runId(), r.workload().type(), r.policyName(), d.time(), d.action(),
                        d.requestedDelta(), d.appliedDelta(), d.changedFleet(), d.vmsBefore(), d.vmsAfter(),
                        d.utilization(), d.arrivalRate(), d.trend(), d.relativeSlope(), d.cooldownBlocked(), d.reason());
                }
            }
        }
    }

    private static void writeWorkloads(Path file, String experimentId, List<RunResult> runs) throws IOException {
        try (CsvWriter w = new CsvWriter(file, List.of("experiment_id", "workload_type", "workload_seed",
            "duration_s", "arrival_pattern", "rate_params", "max_rate", "request_mean_length_mi",
            "request_length_variation", "request_pes", "requests_generated", "expected_requests"))) {
            final Map<String, RunResult> firstPerWorkload = new LinkedHashMap<>();
            for (RunResult r : runs) {
                firstPerWorkload.putIfAbsent(r.workload().type().name(), r);
            }
            for (RunResult r : firstPerWorkload.values()) {
                final WorkloadSpec ws = r.workload();
                w.writeRow(experimentId, ws.type(), ws.seed(), ws.durationSeconds(), ws.arrivalPattern(),
                    ws.paramsString(), ws.maxRate(), ws.meanLengthMi(), ws.lengthVariation(), ws.requestPes(),
                    r.requests().size(), ws.expectedRequests());
            }
        }
    }

    private static void writeVms(Path file, CostModel cost, List<RunResult> runs) throws IOException {
        try (CsvWriter w = new CsvWriter(file, List.of("run_id", "workload_type", "policy", "vm_id", "pes",
            "request_time_s", "activated_time_s", "drain_start_time_s", "termination_time_s", "lifetime_s",
            "billed_s", "cost_usd"))) {
            for (RunResult r : runs) {
                for (VmRecord v : r.vms()) {
                    w.writeRow(r.runId(), r.workload().type(), r.policyName(), v.vmId(), v.pes(), v.requestTime(),
                        v.activatedTime(), v.drainStartTime(), v.terminationTime(), v.lifetimeSeconds(),
                        cost.billedSeconds(v.lifetimeSeconds()), cost.cost(v.lifetimeSeconds()));
                }
            }
        }
    }

    private static void writeRequests(Path file, List<RunResult> runs) throws IOException {
        try (CsvWriter w = new CsvWriter(file, List.of("run_id", "request_id", "length_mi", "arrival_time_s",
            "dispatch_time_s", "vm_id", "start_time_s", "finish_time_s", "response_time_s"))) {
            for (RunResult r : runs) {
                for (RequestRecord q : r.requests()) {
                    w.writeRow(r.runId(), q.requestId(), q.lengthMi(), q.arrivalTime(), q.dispatchTime(), q.vmId(),
                        q.startTime(), q.finishTime(), q.completed() ? q.responseTime() : Double.NaN);
                }
            }
        }
    }

    private static void writeDefinitions(Path file) throws IOException {
        try (CsvWriter w = new CsvWriter(file, List.of("column", "kind", "definition"))) {
            for (Map.Entry<String, String[]> e : SUMMARY_COLUMNS.entrySet()) {
                w.writeRow(e.getKey(), e.getValue()[0], e.getValue()[1]);
            }
        }
    }

    private static void writeConfig(Path file, String experimentId, SimulationConfig cfg) throws IOException {
        try (Writer w = Files.newBufferedWriter(file, StandardCharsets.UTF_8)) {
            w.write("# Effective configuration of experiment " + experimentId + "\n");
            w.write("# Re-run with: --config <this file>\n");
            for (Map.Entry<String, String> e : cfg.asMap().entrySet()) {
                w.write(e.getKey() + "=" + e.getValue() + "\n");
            }
        }
    }

    private static String kv(Map<String, String> m) {
        final StringBuilder sb = new StringBuilder();
        m.forEach((k, v) -> {
            if (!sb.isEmpty()) {
                sb.append(';');
            }
            sb.append(k).append('=').append(v);
        });
        return sb.toString();
    }
}
