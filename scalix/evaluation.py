# --------------------------------------------------------------------------- running

def _run_one(name: str, out_root: str, spec_override=None) -> str:
    from scalix.evaluation import SUITE as suite  # re-import inside worker processes

    exp = suite[name]
    spec = spec_override(exp.spec()) if spec_override else exp.spec()
    result = run_experiment(spec)
    folder = save_experiment(result, Path(out_root) / name, experiment_id=name, large_files=exp.large_files)
    manifest = json.loads((folder / "experiment.json").read_text())
    manifest["question"] = exp.question
    (folder / "experiment.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    # Small derived table (committed), so the report can be regenerated without the large events.csv.
    scale_down_holds(result.events).to_csv(folder / "scale_down_holds.csv", index=False)
    return str(folder)


def run_suite(names: list[str] | None = None, out_root: Path = RESULTS_ROOT, spec_override=None,
              workers: int | None = None) -> list[Path]:
    """Run the named experiments (default: all) and save their outputs. Returns the folders.

    Experiments are independent and deterministic, so they run in parallel processes when more than
    one CPU is available; the outputs are identical either way.
    """
    names = list(names or SUITE)
    workers = workers if workers is not None else min(len(names), os.cpu_count() or 1)
    if workers <= 1 or spec_override is not None:
        return [Path(_run_one(n, str(out_root), spec_override)) for n in names]
    with ProcessPoolExecutor(max_workers=workers) as pool:
        return [Path(f) for f in pool.map(_run_one, names, [str(out_root)] * len(names))]


