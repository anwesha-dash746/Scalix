def paired_table(datasets: dict[str, dict]) -> str:
    """SCALIX in a variant experiment minus SCALIX in its base experiment, paired by seed (identical traces)."""
    lines = ["## Paired differences: SCALIX variant minus SCALIX in the base experiment", "",
             "Same seeds (or days) and identical workload traces, so each one gives a paired difference. Cells: "
             "mean difference ± 95% CI; **bold** = the interval excludes 0 (a real difference in this simulation).", "",
             "| Variant | Base | Scenario | " + " | ".join(label for _, label, _ in PAIRED_METRICS) + " |",
             "|---|---|---|" + "---|" * len(PAIRED_METRICS)]
    for variant, base in PAIRS:
        if variant not in datasets or base not in datasets:
            continue
        main = datasets[base]["summary"]
        other = datasets[variant]["summary"]
        for scenario in _scenarios(other):
            a = main[(main.scenario == scenario) & (main.policy == "SCALIX")].set_index("seed")
            b = other[(other.scenario == scenario) & (other.policy == "SCALIX")].set_index("seed")
            cells = []
            for metric, _, fmt in PAIRED_METRICS:
                diff = (b[metric] - a[metric]).dropna().to_numpy(dtype=float)
                mean, half, n = _ci_stats(diff)
                text = format(mean, "+" + fmt) + ("" if math.isnan(half) else f" ± {format(half, fmt)}")
                significant = not math.isnan(half) and (mean - half > 0 or mean + half < 0)
                cells.append(f"**{text}**" if significant else text)
            lines.append(f"| {variant} | {base} | {SCENARIO_NAMES[scenario]} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


