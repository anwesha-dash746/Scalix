"""Evaluation: a fixed experiment suite, run reproducibly, and a report generated from its outputs.

Run from the project root:

    python -m scalix.evaluation run       # runs every experiment in SUITE (several minutes: NASA days are long)
    python -m scalix.evaluation report    # tables + figures from the saved outputs

Rules that keep the evaluation honest:

* The suite, its settings and its seeds are fixed here in code, before anything runs: synthetic
  scenarios use seeds 1-10, the NASA real-traffic experiments use every complete day of July 1995
  (1-27). Nothing is filtered or re-run to pick better-looking runs.
* Tuned settings come from ``scalix.tuning``, which only ever sees training seeds 101-110 of the
  synthetic scenarios. The test seeds and the NASA days are never used for tuning.
* Every policy sees the identical workload trace per (scenario, seed). Experiments that share the
  workload settings also share traces, so their variants can be compared run for run.
* The report reads only the saved CSV files (and ``results/tuning/tuned.json``) and copies their
  numbers into tables and figures. Everything is SIMULATED; nothing here measures or contacts AWS.

Outputs: ``results/experiments/<name>/`` (summary.csv, aggregate.csv, scale_down_holds.csv and
experiment.json are committed; the large time series, event and workload files are regenerated by
``run`` and git-ignored, and not written at all for the day-long NASA runs). Report:
``docs/results/RESULTS_TABLES.md`` and ``docs/figures/*.png``.

Phase history: the original suite (Phase 6) had the first four experiments. Phase 7 replaced the
response-time proxy with a queueing model and the illustrative price with AWS list prices, and added
tuning, the NASA real-traffic trace, the CPU-derived demand signal and AWS-like timing.
"""

